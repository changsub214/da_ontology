def _extract_ledger_rows_from_gql(gql_rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Extracts clean Spanner/BigQuery ledger columns directly from the unified Step 1 GQL result rows."""
    cleaned: list[dict[str, Any]] = []
    seen: set[str] = set()
    for r in gql_rows:
        row_dict = {
            k: v
            for k, v in r.items()
            if k not in _ECOM_GRAPH_META_COLS and not k.endswith("_obj_url")
        }
        if not row_dict:
            row_dict = {k: v for k, v in r.items() if not k.endswith("_obj_url")}
        sig = json.dumps(row_dict, sort_keys=True, ensure_ascii=False, default=str)
        if sig not in seen:
            seen.add(sig)
            cleaned.append(row_dict)
    return cleaned


def _fmt_ecom_val(col: str, val: Any) -> str:
    """Formats SQL result values cleanly for Markdown tables in Module 05 & 06."""
    if val is None:
        return "-"
    if isinstance(val, bool) or str(val).lower() in ("true", "false"):
        b = val if isinstance(val, bool) else (str(val).lower() == "true")
        return "충족 (True)" if b else "미충족 (False)"
    col_l = col.lower()
    try:
        if any(k in col_l for k in ("krw", "price", "cost", "discount", "refund", "fee", "absorbed", "share_krw")):
            num = int(float(val))
            return f"{num:,}원"
        if "points" in col_l:
            num = int(float(val))
            return f"{num:,}P"
        if any(k in col_l for k in ("pct", "rate", "floor")):
            fval = float(val)
            return f"{fval:.1f}%"
    except Exception:
        pass
    return str(val)


def _rows_to_markdown_table(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return "_조회 결과 0건 (해당 조건을 위반하거나 일치하는 레코드 없음)_"
    cols = list(rows[0].keys())
    header = "| " + " | ".join(f"`{c}`" for c in cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    body = []
    for r in rows[:15]:
        cells = [_fmt_ecom_val(c, r.get(c)) for c in cols]
        body.append("| " + " | ".join(cells) + " |")
    return "\n".join([header, sep, *body])


