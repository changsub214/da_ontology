def _retrieve_top_ecom_examples(question: str, top_k: int = 3) -> list[dict[str, Any]]:
    q_tokens = set(question.replace("?", " ").replace(",", " ").split())
    scored: list[tuple[float, str, dict[str, Any]]] = []
    eq_map = _load_eq_compare()
    for scen_num, scen in _ECOM_SCENARIOS.items():
        if scen_num == "21":
            continue
        eq_q = (eq_map.get(scen["eq_id"], {}) or {}).get("question", "")
        text_bag = f"{eq_q} {scen.get('graph_path', '')} {scen.get('why_hard', '')}"
        overlap = sum(1.0 for tok in q_tokens if len(tok) >= 2 and tok in text_bag)
        scored.append((overlap, scen_num, {"id": scen["cq_id"], "question": eq_q, "gql": scen["gql"], "provisions": scen.get("provisions", [])}))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [item[2] for item in scored[:top_k]]


def _call_gemini_json(token: str, prompt_text: str, timeout_s: int = 45) -> dict[str, Any]:
    url = f"https://aiplatform.googleapis.com/v1/projects/{PROJECT}/locations/global/publishers/google/models/{GEMINI_MODEL_ID}:generateContent"
    body = {
        "contents": [{"role": "user", "parts": [{"text": prompt_text}]}],
        "generationConfig": {
            "temperature": 0.0,
            "seed": GEMINI_SEED,
            "responseMimeType": "application/json",
            "thinkingConfig": {"thinkingBudget": 0},
        },
    }
    req = urllib.request.Request(
        url,
        data=json.dumps(body, ensure_ascii=False).encode("utf-8"),
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=timeout_s) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    _, raw_text = _extract_fn_call_or_text(data)
    cleaned = raw_text.strip()
    if cleaned.startswith("```"):
        cleaned = cleaned.strip("`").removeprefix("json").strip()
    return json.loads(cleaned)


