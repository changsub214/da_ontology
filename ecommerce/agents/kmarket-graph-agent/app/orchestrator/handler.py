    if not cands:
        return None, ""
    parts = ((cands[0].get("content") or {}).get("parts")) or []
    fn_call = None
    texts: list[str] = []
    for p in parts:
        if not isinstance(p, dict):
            continue
        if "functionCall" in p and fn_call is None:
            fn_call = p["functionCall"]
        if p.get("text"):
            texts.append(str(p["text"]))
    return fn_call, "".join(texts).strip()


