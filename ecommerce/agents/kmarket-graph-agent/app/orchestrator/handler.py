def _load_ecom_aliases_from_bq(
    run_bq_sql_fn: Callable[..., tuple[list[dict], dict]] | None = None,
) -> list[tuple[str, str, str]]:
    """Loads the 355-row `kmarket_ontology.ont_entity_aliases` table from BigQuery (with TTL cache)."""
    global _ECOM_BQ_ALIAS_CACHE, _ECOM_BQ_ALIAS_CACHE_TS
    now = time.time()
    if _ECOM_BQ_ALIAS_CACHE is not None and (now - _ECOM_BQ_ALIAS_CACHE_TS) < 600:
        return _ECOM_BQ_ALIAS_CACHE
    if run_bq_sql_fn is not None:
        try:
            rows, _ = run_bq_sql_fn(
                f"SELECT alias_text AS alias, entity_class, canonical_id "
                f"FROM `{PROJECT}.kmarket_ontology.ont_entity_aliases` "
                f"ORDER BY CHAR_LENGTH(alias_text) DESC"
            )
            if rows:
                _ECOM_BQ_ALIAS_CACHE = [
                    (str(r["alias"]), str(r["entity_class"]), str(r["canonical_id"]))
                    for r in rows
                    if r.get("alias") and r.get("entity_class") and r.get("canonical_id")
                ]
                _ECOM_BQ_ALIAS_CACHE_TS = now
                return _ECOM_BQ_ALIAS_CACHE
        except Exception:
            pass
    return sorted(_ECOM_ALIAS_ENTRIES, key=lambda x: len(x[0]), reverse=True)


def _resolve_ecom_aliases(
    question: str,
    run_bq_sql_fn: Callable[..., tuple[list[dict], dict]] | None = None,
) -> list[dict[str, str]]:
    """Step 0 (`before_agent_callback`): Non-overlapping longest-match entity alias resolution (`ont_entity_aliases`)."""
    q = str(question or "")
    if not q:
        return []
    entries = _load_ecom_aliases_from_bq(run_bq_sql_fn)
    hits: list[dict[str, str]] = []
    seen_canonical: set[tuple[str, str]] = set()
    occupied: list[tuple[int, int]] = []

    for surface, ent_cls, canon_id in entries:
        idx = q.find(surface)
        if idx < 0:
            continue
        span = (idx, idx + len(surface))
        if any(not (span[1] <= s or span[0] >= e) for s, e in occupied):
            continue
        occupied.append(span)
        if (ent_cls, canon_id) not in seen_canonical:
            seen_canonical.add((ent_cls, canon_id))
            hits.append(_ah(surface, ent_cls, canon_id))

    # Contextual disambiguation for generic '코트' -> PRD-3001 when 김서연 or 장바구니/니트 is mentioned
    if ("김서연" in q or "USR-1001" in q or "코디 니트" in q) and "코트" in q:
        if ("Product", "PRD-3001") not in seen_canonical:
            seen_canonical.add(("Product", "PRD-3001"))
            hits.append(_ah("코트", "Product", "PRD-3001"))
    return hits[:8]


