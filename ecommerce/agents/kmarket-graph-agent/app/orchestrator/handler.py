def _detect_scenario_num(data: dict[str, Any]) -> str | None:
    """Strictly detects preset scenario numbers (`01`..`21`, `01_KIM`) without hijacking free-form questions."""
    num = str(data.get("num") or "").strip().rstrip(".")
    if num == "Q21_D5":
        return "21"
    if num in _ECOM_SCENARIOS:
        return num
    q = str(data.get("question") or data.get("query") or "").strip()
    if not q:
        return "01"
    q_norm = _norm_question(q)

    # 1. Governance D5 fixture (`v0.1.0` / `폐기된`)
    if "v0.1.0" in q or "폐기된" in q_norm or "구버전" in q_norm:
        return "21"

    # 2. Module 04 CQ01 김서연 (`USR-1001`) 코트(`PRD-3001`) + 코디 니트(`PRD-3002`) 번들 심사
    if (
        ("김서연" in q or "USR-1001" in q or "SES-1001-A" in q or "EVT-5002" in q)
        and any(k in q for k in ("코트", "PRD-3001"))
        and any(k in q for k in ("니트", "번들", "PRD-3002"))
    ):
        return "01_KIM"

    # 3. Exact normalized match against benchmark EQ questions
    for scen_num, q_list in _BENCHMARK_EQ_QUESTIONS.items():
        if any(_norm_question(cand) == q_norm for cand in q_list):
            return scen_num

    eq_map = _load_eq_compare()
    for scen_num, scen in _ECOM_SCENARIOS.items():
        if scen_num in ("01_KIM", "21"):
            continue
        eq_item = eq_map.get(scen["eq_id"], {})
        eq_q = str(eq_item.get("question") or "").strip()
        if eq_q and _norm_question(eq_q) == q_norm:
            return scen_num

    # Free-form user questions return None and go through the live Gemini Turn Planner!
    return None


def _load_ecom_provision_catalog(
    run_bq_sql_fn: Callable[..., tuple[list[dict], dict]],
) -> list[dict[str, str]]:
    """Loads all 36 `Provision` nodes from `kmarket_ontology.v_node_provision` (cached)."""
    global _ECOM_PROVISION_CATALOG_CACHE
    if _ECOM_PROVISION_CATALOG_CACHE is not None:
        return _ECOM_PROVISION_CATALOG_CACHE
    try:
        rows, _ = run_bq_sql_fn(
            f"SELECT provision_slot_id, doc_id, article_no, title, provision_role "
            f"FROM `{PROJECT}.kmarket_ontology.v_node_provision` "
            f"ORDER BY doc_id, provision_slot_id"
        )
        if rows:
            _ECOM_PROVISION_CATALOG_CACHE = [
                {
                    "provision_slot_id": str(r.get("provision_slot_id") or ""),
                    "doc_id": str(r.get("doc_id") or ""),
                    "article_no": str(r.get("article_no") or ""),
                    "title": str(r.get("title") or ""),
                    "provision_role": str(r.get("provision_role") or ""),
                }
                for r in rows
                if r.get("provision_slot_id")
            ]
            return _ECOM_PROVISION_CATALOG_CACHE
    except Exception:
        pass
    return []


