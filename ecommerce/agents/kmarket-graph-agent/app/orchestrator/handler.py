    q_vec = q_vecs[0] if q_vecs else []
    scored = []
    for item in corpus:
        sim = _cosine_sim(q_vec, item.get("embedding", []))
        scored.append({
            "doc_id": item["doc_id"],
            "source": item["source"],
            "pages": item.get("pages", "1"),
            "score": round(float(sim), 4),
            "text": item["text"],
        })
    scored.sort(key=lambda x: x["score"], reverse=True)
    return scored[:top_k]


