def _validate_ecom_gql_syntax_and_hops(gql_text: str, max_hops: int = 12) -> tuple[bool, int, list[str]]:
    """Validates ISO/IEC 39075 GQL structure and hop count (`<= max_hops`) before BigQuery execution."""
    txt = str(gql_text or "").strip()
    errors: list[str] = []
    if not txt:
        return False, 0, ["Empty GQL query"]
    upper = txt.upper()
    if not upper.startswith("GRAPH "):
        errors.append("GQL must begin with `GRAPH kmarket_ontology.ecommerce_graph`")
    if "MATCH " not in upper:
        errors.append("GQL must contain a `MATCH` clause")
    if "RETURN " not in upper:
        errors.append("GQL must contain a `RETURN` clause")
    for dml in ("INSERT ", "UPDATE ", "DELETE ", "DROP ", "ALTER ", "CREATE ", "MERGE ", "TRUNCATE "):
        if dml in upper:
            errors.append(f"Disallowed mutating keyword in GQL: {dml.strip()}")
    # Count edge patterns: `-[...]->`, `<-[...]-`, `->`, `<-`
    hop_matches = re.findall(r"-\[[^\]]*\]->|<-\[[^\]]*\]-|->|<-", txt)
    hops = max(1, len(hop_matches))
    if hops > max_hops:
        errors.append(f"GQL hop count ({hops}) exceeds max_hops ({max_hops})")
    return len(errors) == 0, hops, errors


def _dry_run_bq_gql(token: str, gql_text: str) -> tuple[bool, int, str]:
    """Executes a BigQuery `dryRun: True` job via REST API to validate GQL and measure `totalBytesProcessed`."""
    url = f"https://bigquery.googleapis.com/bigquery/v2/projects/{PROJECT}/jobs"
    body = {
        "configuration": {
            "query": {
                "query": gql_text,
                "useLegacySql": False,
            },
            "dryRun": True,
        }
    }
    req = urllib.request.Request(
        url,
        data=json.dumps(body, ensure_ascii=False).encode("utf-8"),
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            payload = json.loads(resp.read().decode("utf-8"))
        stats = (payload.get("statistics") or {}).get("query") or {}
        est_bytes = int(stats.get("totalBytesProcessed") or payload.get("statistics", {}).get("totalBytesProcessed") or 0)
        return True, est_bytes, ""
    except urllib.error.HTTPError as he:
        err_body = he.read().decode("utf-8", errors="replace")
        try:
            err_json = json.loads(err_body)
            msg = ((err_json.get("error") or {}).get("message")) or err_body[:300]
        except Exception:
            msg = err_body[:300]
        return False, 0, msg
    except Exception as e:
        return False, 0, str(e)


