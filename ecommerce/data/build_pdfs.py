def render_pdf(spec: dict) -> dict:
    os.makedirs(UN_DATA_DIR, exist_ok=True)
    out_path = os.path.join(UN_DATA_DIR, spec["filename"])
    doc = fitz.open()

    for page_idx, blocks in enumerate(spec["pages"], start=1):
        page = doc.new_page(width=595, height=842)  # A4 portrait
        page.insert_font(fontname="ko_reg", fontfile=FONT_REG)
        page.insert_font(fontname="ko_bold", fontfile=FONT_BOLD)

        # Header box
        page.draw_rect(fitz.Rect(42, 36, 553, 94), color=(0.18, 0.28, 0.48), fill=(0.95, 0.97, 1.0), width=1.0)
        page.insert_text(fitz.Point(52, 54), spec["doc_header"], fontname="ko_reg", fontsize=8.5, color=(0.25, 0.35, 0.55))
        page.insert_text(fitz.Point(52, 72), spec["doc_title"], fontname="ko_bold", fontsize=12.0, color=(0.08, 0.14, 0.28))
        page.insert_text(fitz.Point(52, 87), spec["doc_subtitle"], fontname="ko_reg", fontsize=8.5, color=(0.35, 0.40, 0.48))

        y = 118.0
        for btype, text in blocks:
            if btype == "H":
                page.draw_rect(fitz.Rect(42, y - 12, 553, y + 8), color=(0.82, 0.86, 0.94), fill=(0.92, 0.95, 0.99), width=0.5)
                page.insert_text(fitz.Point(48, y + 2), text, fontname="ko_bold", fontsize=10.5, color=(0.10, 0.20, 0.42))
                y += 24.0
            else:
                for raw_line in text.split("\n"):
                    wrapped_lines = textwrap.wrap(raw_line, width=48, break_long_words=False, replace_whitespace=False) or [""]
                    for wline in wrapped_lines:
                        page.insert_text(fitz.Point(48, y), wline, fontname="ko_reg", fontsize=9.5, color=(0.12, 0.14, 0.18))
                        y += 15.5
                y += 8.0

        # Footer
        total_pages = len(spec["pages"])
        footer_text = f"{spec['doc_title']} — Page {page_idx} / {total_pages}"
        page.draw_line(fitz.Point(42, 800), fitz.Point(553, 800), color=(0.80, 0.82, 0.86), width=0.6)
        page.insert_text(fitz.Point(48, 816), footer_text, fontname="ko_reg", fontsize=8.0, color=(0.45, 0.48, 0.54))

    doc.save(out_path, garbage=4, deflate=True)
    doc.close()

    with open(out_path, "rb") as f:
        data = f.read()
    sha = hashlib.sha256(data).hexdigest()
    return {
        "filename": spec["filename"],
        "pages": len(spec["pages"]),
        "bytes": len(data),
        "sha256_prefix": sha[:16],
        "sha256": sha,
    }


def main() -> None:
    stats_by_file: dict[str, dict] = {}
    total_pages = 0
    for spec in PDF_SPECS:
        st = render_pdf(spec)
        stats_by_file[st["filename"]] = st
        total_pages += st["pages"]
        print(f"[build_pdfs] {st['filename']}: {st['pages']} pages, {st['bytes']:,} bytes, sha256={st['sha256_prefix']}")

    if os.path.exists(MANIFEST_PATH):
        with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
            manifest = yaml.safe_load(f)
        for doc_entry in manifest.get("documents", []):
            fname = doc_entry.get("filename")
            if fname in stats_by_file:
                st = stats_by_file[fname]
                doc_entry["pages"] = st["pages"]
                doc_entry["bytes"] = st["bytes"]
                doc_entry["sha256_prefix"] = st["sha256_prefix"]
        with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
            yaml.safe_dump(manifest, f, allow_unicode=True, sort_keys=False, default_flow_style=False)
        print(f"[build_pdfs] Updated {MANIFEST_PATH} (total 10 PDFs, {total_pages} pages)")


if __name__ == "__main__":
    main()
